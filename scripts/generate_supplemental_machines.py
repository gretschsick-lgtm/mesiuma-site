def main() -> None:
    repo_root = Path(__file__).parent.parent
    output_path = repo_root / "public" / "supplemental_machines.csv"

    print("=== 既存DB正規化セットを構築中... ===")
    existing = build_existing_normalized_set()
    print(f"  既存正規化済み件数: {len(existing)}")

    print("\n=== 重複チェック実行中... ===")
    unique, skipped = deduplicate(SUPPLEMENTAL_MACHINES, existing)

    print(f"\n  候補総数:      {len(SUPPLEMENTAL_MACHINES)}")
    print(f"  重複スキップ:  {len(skipped)}")
    print(f"  追加対象:      {len(unique)}")

    if skipped:
        print("\n  [スキップ詳細]")
        for name, reason in skipped:
            print(f"    SKIP({reason}): {name}")

    write_csv(unique, output_path)
    print(f"\n=== CSV 出力完了: {output_path} ===")

    # 統計サマリー
    from collections import Counter
    type_counts = Counter(row[2] for row in unique)
    maker_counts = Counter(row[1] for row in unique)
    print(f"\n  type 別内訳: slot={type_counts.get('slot', 0)}, pachinko={type_counts.get('pachinko', 0)}")
    print(f"\n  メーカー別 上位10:")
    for maker, cnt in maker_counts.most_common(10):
        print(f"    {maker}: {cnt}")

    total_db_after = len(existing) + len(unique)
    print(f"\n  追加後の概算総機種数: {len(existing)} + {len(unique)} = {total_db_after}")


if __name__ == "__main__":
    main()
