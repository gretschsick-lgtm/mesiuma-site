# machines.json（スロット200件）の正規化済み名称を追加ロード
def _load_machines_json_normalized() -> set[str]:
    """public/machines.json からスロット機種名を正規化して返す。"""
    import json

    path = Path(__file__).parent.parent / "public" / "machines.json"
    if not path.exists():
        return set()
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    return {normalize_for_comparison(m["name"]) for m in data.get("machines", [])}


# machines_master.csv の正規化済み名称を追加ロード
def _load_csv_normalized() -> set[str]:
    path = Path(__file__).parent.parent / "public" / "machines_master.csv"
    if not path.exists():
        return set()
    result = set()
    with open(path, encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            result.add(normalize_for_comparison(row.get("official_name", "")))
    return result


