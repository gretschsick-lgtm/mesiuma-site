# ── 重複チェックロジック ──────────────────────────────────────────────────

def build_existing_normalized_set() -> set[str]:
    """既存DBの正規化済み名称セットを構築する。"""
    existing = set()
    existing |= _EXISTING_SLOT_NORMALIZED
    existing |= _EXISTING_PACHINKO_NORMALIZED

    # machines.json（スロット200件）
    existing |= _load_machines_json_normalized()

    # machines_master.csv
    existing |= _load_csv_normalized()

    # 空文字は除去
    existing.discard("")
    return existing


def deduplicate(
    candidates: list[tuple[str, str, str, str]],
    existing: set[str],
) -> tuple[list[tuple[str, str, str, str]], list[tuple[str, str]]]:
    """
    重複を除去して (unique, skipped) を返す。
    同一スクリプト内での重複（official_name ベース）も除去する。
    """
    unique: list[tuple[str, str, str, str]] = []
    skipped: list[tuple[str, str]] = []
    seen_in_script: set[str] = set()

    for row in candidates:
        official_name = row[0]
        norm = normalize_for_comparison(official_name)

        if not norm:
            skipped.append((official_name, "空文字正規化"))
            continue

        if norm in existing:
            skipped.append((official_name, "既存DB重複"))
            continue

        if norm in seen_in_script:
            skipped.append((official_name, "スクリプト内重複"))
            continue

        seen_in_script.add(norm)
        unique.append(row)

    return unique, skipped


# ── CSV 書き出し ──────────────────────────────────────────────────────────

def write_csv(rows: list[tuple[str, str, str, str]], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["official_name", "manufacturer", "type", "series_hint"])
        for official_name, manufacturer, machine_type, series_hint in rows:
            # type バリデーション
            assert machine_type in ("slot", "pachinko"), (
                f"invalid type '{machine_type}' for '{official_name}'"
            )
            writer.writerow([official_name, manufacturer, machine_type, series_hint])


